module systolicarray_tb;

  parameter N  = 2;
    parameter AW = 16;
    parameter BW = 16;
    parameter CW = 32;


    // =====================================================
    // Signals
    // =====================================================

    reg clk;
    reg rst;
    reg vld_in;

    // A = 2 x 16 = 32 bits
    reg signed [N*AW-1:0] a_in;

    // B = 2 x 16 = 32 bits
    reg signed [N*BW-1:0] b_in;

    // C = 2 x 2 x 32 = 128 bits
    wire signed [N*N*CW-1:0] c_out;


    // =====================================================
    // DUT
    // =====================================================

    systolic_matmul #(
        .N(N),
        .AW(AW),
        .BW(BW),
        .CW(CW)
    ) DUT (
        .clk(clk),
        .rst(rst),
        .vld_in(vld_in),
        .a_in(a_in),
        .b_in(b_in),
        .c_out(c_out)
    );


    // =====================================================
    // CLOCK
    // =====================================================

    initial begin
        clk = 0;

        forever #5 clk = ~clk;
    end


    // =====================================================
    // TEST
    // =====================================================

    initial begin

        // -------------------------------------------------
        // Initial values
        // -------------------------------------------------

        rst    = 1;
        vld_in = 0;

        a_in = 0;
        b_in = 0;


        // -------------------------------------------------
        // RESET
        // -------------------------------------------------

        #12;

        rst    = 0;
        vld_in = 1;


        // =================================================
        // CYCLE 0
        //
        // A:
        //
        // A00 = 1
        // A10 = 3 does NOT enter yet
        //
        // B:
        //
        // B00 = 5
        // B01 = 6 does NOT enter yet
        // =================================================

        // a_in[15:0]  = row 0
        // a_in[31:16] = row 1

        a_in[15:0]  = 1;
        a_in[31:16] = 0;

        // b_in[15:0]  = column 0
        // b_in[31:16] = column 1

        b_in[15:0]  = 5;
        b_in[31:16] = 0;

        #10;


        // =================================================
        // CYCLE 1
        //
        // A00 -> PE01
        // A10 -> PE10
        //
        // B00 -> PE10
        // B01 -> PE01
        // =================================================

        a_in[15:0]  = 2;   // A01
        a_in[31:16] = 3;   // A10

        b_in[15:0]  = 7;   // B10
        b_in[31:16] = 6;   // B01

        #10;


        // =================================================
        // CYCLE 2
        //
        // A11 enters
        // B11 enters
        // =================================================

        a_in[15:0]  = 0;
        a_in[31:16] = 4;   // A11

        b_in[15:0]  = 0;
        b_in[31:16] = 8;   // B11

        #10;


        // =================================================
        // CYCLE 3
        //
        // Data already inside the array propagates
        // to PE11.
        // =================================================

        a_in = 0;
        b_in = 0;

        #10;


        // =================================================
        // STOP INPUT
        // =================================================

        vld_in = 0;


        // Give some time for outputs
        #20;


        // =================================================
        // DISPLAY RESULT
        // =================================================

        $display("");
        $display("=================================");
        $display("       SYSTOLIC ARRAY TEST");
        $display("=================================");

        $display("Expected:");
        $display("19  22");
        $display("43  50");

        $display("");

        $display("Actual:");

        $display("%0d  %0d",
                 $signed(c_out[31:0]),
                 $signed(c_out[63:32]));

        $display("%0d  %0d",
                 $signed(c_out[95:64]),
                 $signed(c_out[127:96]));

        $display("=================================");
        $display("");


        #10;

        $finish;

    end

endmodule